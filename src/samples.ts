import { inferredYieldCount } from './math'
import { stagesOf } from './process'
import { notesOf } from './recipe'
import type { Ingredient, NoteEntry, Recipe, TestBake, Unit } from './types'

function ing(id: string, name: string, amount: number, unit: Unit = 'g'): Ingredient {
  return { id, name, amount, unit }
}

function recipe(
  partial: Omit<Recipe, 'personalNote' | 'yieldCount' | 'notes' | 'tests' | 'stages' | 'craft' | 'sourceBook' | 'sourcePage' | 'sourceUrl' | 'status' | 'panIds'> & {
    personalNote?: string
    yieldCount?: number
    notes?: NoteEntry[]
    tests?: TestBake[]
    stages?: Recipe['stages']
    craft?: Recipe['craft']
    sourceBook?: string
    sourcePage?: string
    sourceUrl?: string
    status?: Recipe['status']
    panIds?: string[]
  },
): Recipe {
  const personalNote = partial.personalNote ?? ''
  const notes = partial.notes ?? notesOf({ ...partial, personalNote })
  const stages = partial.stages ?? stagesOf(partial)
  return {
    ...partial,
    personalNote: notes.map((note) => note.text).join('\n'),
    yieldCount: partial.yieldCount ?? inferredYieldCount(partial.yieldLabel),
    notes,
    tests: partial.tests ?? [],
    stages,
    craft: partial.craft ?? 'bread',
    sourceBook: partial.sourceBook?.trim() ?? '',
    sourcePage: partial.sourcePage?.trim() ?? '',
    sourceUrl: partial.sourceUrl?.trim() ?? '',
    status: partial.status === 'test' || partial.status === 'done' || partial.status === 'todo' ? partial.status : null,
    panIds: partial.panIds ?? [],
  }
}

